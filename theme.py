#!/usr/bin/env python3
"""Build native application themes from theme/palette.json (Python standard library only)."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent
TOKEN = re.compile(r"\{\{([a-z][a-z0-9_]*)(?:\|(hex|rgb|ansi))?\}\}")


def load_palette(path):
    source = json.loads(path.read_text())
    if not isinstance(source, dict) or not all(isinstance(source.get(key), dict) for key in ("colors", "roles")):
        raise ValueError("Palette must contain colors and roles objects")
    colors, roles = source["colors"], source["roles"]
    for name, color in colors.items():
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or not re.fullmatch(r"#[0-9a-f]{6}", color):
            raise ValueError(f"Invalid palette swatch: {name}={color!r}")
    for name, swatch in roles.items():
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or swatch not in colors:
            raise ValueError(f"Invalid palette role: {name}={swatch!r}")
    return {name: colors[swatch] for name, swatch in roles.items()}


def render(root=ROOT, palette_path=None):
    """Validate and render everything before touching any generated file."""
    palette = load_palette(palette_path or root / "theme/palette.json")
    outputs = {}

    def substitute(match):
        role, format_ = match.groups()
        color = palette[role]
        if format_ == "hex":
            return color[1:]
        rgb = [str(int(color[i:i + 2], 16)) for i in (1, 3, 5)]
        if format_ == "rgb":
            return ",".join(rgb)
        if format_ == "ansi":
            return "38;2;" + ";".join(rgb)
        return color

    for source, destination in json.loads((root / "theme/templates.json").read_text()).items():
        source_path = root / "theme/templates" / source
        destination_path = root / destination
        if ".." in Path(source).parts or not source_path.is_relative_to(root / "theme/templates"):
            raise ValueError(f"Unsafe template path: {source}")
        if ".." in Path(destination).parts or not destination_path.is_relative_to(root / "stow"):
            raise ValueError(f"Unsafe destination: {destination}")
        content = TOKEN.sub(substitute, source_path.read_text())
        if "{{" in content or "}}" in content:
            raise ValueError(f"Unresolved theme token in {source}")
        outputs[destination_path] = content

    desktop = root / "stow/desktop"
    outputs[desktop / ".local/share/graphite/palette.json"] = json.dumps(palette, indent=2) + "\n"
    outputs[desktop / ".config/graphite/theme/colors.css"] = (
        "/* Generated by theme.py; edit theme/palette.json. */\n"
        + "".join(f"@define-color {name} {color};\n" for name, color in palette.items())
    )
    outputs[desktop / ".config/graphite/quick-settings/Theme.js"] = (
        ".pragma library\n// Generated by theme.py; edit theme/palette.json.\n"
        + "".join(f'var {name} = "{color}";\n' for name, color in palette.items())
    )
    lua = ("-- Generated by theme.py; edit theme/palette.json.\nreturn {\n"
           + "".join(f'  {name} = "{color}",\n' for name, color in palette.items()) + "}\n")
    # Neovim works independently of the desktop Stow package.
    outputs[root / "stow/nvim/.config/nvim/lua/graphite/palette.lua"] = lua
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__, epilog="Edit the palette, run this command, then review and commit theme/ and stow/. No home links or services are changed.")
    parser.add_argument("--check", action="store_true", help="Report stale/missing generated files without writing anything")
    args = parser.parse_args()
    try:
        outputs = render()
        changed = [path for path, content in outputs.items() if not path.is_file() or path.read_text() != content]
        if args.check:
            for path in changed:
                print(f"STALE {path.relative_to(ROOT)}")
            if changed:
                print("Run python3 theme.py, then review and commit the source and generated files.")
                return 1
            print(f"PASS: {len(outputs)} generated theme files match theme/palette.json.")
        else:
            for path in changed:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(outputs[path])
            print(f"Updated {len(changed)} of {len(outputs)} theme files. No applications restarted.")
        return 0
    except (ValueError, KeyError, OSError, TypeError) as error:
        print(f"Theme error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
